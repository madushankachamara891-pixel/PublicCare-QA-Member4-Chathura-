CREATE TABLE report_progress_updates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
    status VARCHAR(32) NOT NULL CHECK (status IN ('PENDING', 'IN_PROGRESS', 'RESOLVED')),
    note VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    storage_key VARCHAR(80) UNIQUE,
    content_type VARCHAR(32),
    size_bytes BIGINT,
    CONSTRAINT report_progress_image_metadata CHECK (
        (storage_key IS NULL AND content_type IS NULL AND size_bytes IS NULL) OR
        (storage_key IS NOT NULL AND content_type IS NOT NULL AND content_type IN ('image/jpeg', 'image/png')
            AND size_bytes IS NOT NULL AND size_bytes BETWEEN 1 AND 5242880)
    )
);
CREATE INDEX report_progress_updates_report_created_idx ON report_progress_updates(report_id, created_at, id);
